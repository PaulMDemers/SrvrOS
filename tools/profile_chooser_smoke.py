#!/usr/bin/env python3
"""Exercise the profile chooser on owned, disposable installed QEMU disks.

Requires a source-matched build. Evidence is written under a unique build/review
folder; only processes and images created by this invocation are touched. The
transport bundle is generated by the guest and never modified by the host.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import socket
import subprocess
import tempfile
import time
import zlib

from desktop_foundation_smoke import QMP
from desktop_theme_profiles_smoke import qmp_axis
from displayd_frame_smoke import choose_port, connect_serial, stop_process
from pack_runtime_elf import runtime_elf
from uefi_usb_smoke import default_ovmf_path
import installation_image
import profile_bundle
import profile_desktop_smoke as d
import profile_guest_smoke as guest
import profile_image
import source_provenance

ROOT = Path(__file__).resolve().parents[1]
A, B, TRANSPORT = guest.A, guest.B, guest.TRANSPORT
ALT = '/fat/home/alternative'
ALT_ID = '87654321-4321-4321-8321-cba987654321'


class VM:
    def __init__(self, disk, transport, out, label, args, width=1280, height=800):
        self.disk, self.transport, self.out, self.label = disk, transport, out, label
        self.args, self.width, self.height = args, width, height
        self.output, self.consumed = bytearray(), 0
        self.serial = self.qmp = self.vm = None

    def __enter__(self):
        self.temp = tempfile.TemporaryDirectory(prefix='srv-profile-chooser-', dir='/tmp')
        qmp_path = Path(self.temp.name) / 'qmp'
        port = choose_port(30001, 38000)
        variables = self.out / f'firmware-vars-{self.label}.fd'
        shutil.copyfile(self.args.ovmf_vars, variables)
        cmd = [self.args.qemu, '-machine', 'q35,i8042=off', '-accel', 'tcg', '-m', '1024M',
               '-smp', '1', '-nic', 'none', '-drive', f'if=pflash,format=raw,readonly=on,file={self.args.ovmf}',
               '-drive', f'if=pflash,format=raw,file={variables}', '-device', 'ich9-ahci,id=ahci',
               '-drive', f'if=none,id=installed,format=raw,file={self.disk}',
               '-device', 'ide-hd,drive=installed,bus=ahci.0,bootindex=1',
               '-drive', f'if=none,id=transport,format=raw,file={self.transport}',
               '-device', 'ide-hd,drive=transport,bus=ahci.1,bootindex=2',
               '-vga', 'none', '-device', f'VGA,vgamem_mb=64,xres={self.width},yres={self.height}',
               '-device', 'virtio-keyboard-pci,disable-legacy=on', '-device', 'virtio-tablet-pci,disable-legacy=on',
               '-serial', f'tcp:127.0.0.1:{port},server=on,wait=off',
               '-qmp', f'unix:{qmp_path},server=on,wait=off', '-display', 'none', '-monitor', 'none', '-no-reboot']
        assert not {'-cdrom', '-kernel', '-initrd', '-bios'} & set(cmd)
        d.save_json(self.out / f'command-{self.label}.json', cmd)
        self.log = (self.out / f'qemu-{self.label}.log').open('wb')
        try:
            self.vm = subprocess.Popen(cmd, stdout=self.log, stderr=self.log)
            self.serial = connect_serial(port, 20); self.serial.settimeout(.2)
            self.qmp = QMP(qmp_path)
            self.wait(b'srv> ', self.args.boot_wait)
            for marker in (b'init: readiness=ready', b'exfat: mounted /fat from ahci0p2 ',
                           b'installed-root: selected device=ahci0p2 format=exfat-v1 role=system',
                           b'block: registered GPT partition ahci1p2 '):
                if marker not in self.output: raise RuntimeError(f'{self.label}: missing boot marker {marker!r}')
            if b'trying initramfs fallback' in self.output: raise RuntimeError('fallback boot')
            self.serial.sendall(b'mount ahci1p2 /work\n')
            self.wait(b'mount: ahci1p2 on /work type=exfat'); self.wait(b'srv> ')
            return self
        except BaseException:
            self.__exit__(*__import__('sys').exc_info())
            raise

    def wait(self, marker, timeout=60):
        start = time.monotonic()
        while marker not in self.output[self.consumed:]:
            if time.monotonic() - start > timeout or self.vm.poll() is not None:
                raise RuntimeError(f'{self.label}: missing {marker!r}')
            try:
                chunk = self.serial.recv(16384)
                if not chunk: raise RuntimeError('serial disconnected')
                self.output.extend(chunk)
                (self.out / f'serial-{self.label}.log').write_bytes(self.output)
            except socket.timeout: pass
        self.consumed = self.output.index(marker, self.consumed) + len(marker)

    def run(self, line, success=True, code=None):
        command = 'run ' + line
        if len(command.encode('ascii')) >= 128: raise RuntimeError('monitor command exceeds line limit')
        start = len(self.output)
        self.serial.sendall((command + '\n').encode())
        self.wait(b' exited status='); self.wait(b'\nsrv> ')
        match = re.search(rb'run: pid=\d+ exited status=(\d+)', self.output[start:])
        if not match or (int(match.group(1)) == 0) != success or (code is not None and int(match.group(1)) != code):
            raise RuntimeError(f'{self.label}: unexpected exit status: {command}')

    def key(self, key):
        self.qmp.call('human-monitor-command', {'command-line': 'sendkey ' + key})
        time.sleep(.3)

    def click(self, x, y):
        self.qmp.call('input-send-event', {'events': [
            {'type': 'abs', 'data': {'axis': 'x', 'value': qmp_axis(x, self.width)}},
            {'type': 'abs', 'data': {'axis': 'y', 'value': qmp_axis(y, self.height)}}]})
        time.sleep(.2)
        for down in (True, False):
            self.qmp.call('input-send-event', {'events': [{'type': 'btn', 'data': {'button': 'left', 'down': down}}]})
            time.sleep(.2)

    def screenshot(self, name):
        path = self.out / f'{name}-{self.label}.ppm'
        self.qmp.call('screendump', {'filename': str(path)})
        with path.open('rb') as stream:
            header = stream.read(256)
        match = re.match(rb'P6\s+(\d+)\s+(\d+)\s+255\s', header)
        if not match or tuple(map(int, match.groups())) != (self.width, self.height):
            raise RuntimeError(f'{self.label}: screenshot dimensions differ from requested {self.width}x{self.height}')

    def quiesced_data_hash(self):
        # Flush guest writes before pausing all vCPUs. Never inspect the disk
        # while QEMU can mutate it; always resume even if reading fails.
        self.run('/fat/bin/sync')
        self.qmp.call('stop')
        try:
            status = self.qmp.call('query-status')
            if status.get('status') != 'paused':
                raise RuntimeError(f'{self.label}: QEMU did not pause')
            _, (offset, size) = d.partitions(self.disk)
            return d.digest(d.data_image(self.disk, offset, size))
        finally:
            self.qmp.call('cont')

    def launch(self, flags):
        line = 'run /fat/bin/deskd ' + flags
        if len(line.encode()) >= 128: raise RuntimeError('monitor command exceeds line limit')
        self.serial.sendall((line + '\n').encode())

    def close_desktop(self):
        self.key('f10'); self.key('end'); self.key('ret')
        self.wait(b'deskd: exited'); self.wait(b'srv> ')

    def finish(self):
        for mount in ('/work', '/fat'):
            start = len(self.output)
            self.serial.sendall(('fsck ' + mount + '\n').encode())
            self.wait(b'exfat-check:'); self.wait(b'srv> ')
            if not re.search(rb'exfat-check: mounts=1 files=\d+ clusters=\d+ leaks=0 fat=0 errors=0 ok', self.output[start:]):
                raise RuntimeError(f'{self.label}: guest fsck failed: {mount}')
        self.serial.sendall(b'unmount /work\n'); self.wait(b'exfat: unmounted /work '); self.wait(b'srv> ')
        if any(x in self.output for x in (b'exception:', b'failure=1', b'deskd: FAIL')):
            raise RuntimeError(f'{self.label}: guest reported failure')
        self.serial.sendall(b'reboot\n'); self.vm.wait(timeout=30)
        if self.vm.returncode: raise RuntimeError(f'{self.label}: reboot failed')

    def __exit__(self, typ, value, tb):
        if typ and self.qmp and self.vm and self.vm.poll() is None:
            try: self.screenshot('failure')
            except Exception: pass
        if self.serial: self.serial.close()
        if self.qmp: self.qmp.stream.close(); self.qmp.sock.close()
        if self.vm: stop_process(self.vm)
        self.log.close()
        (self.out / f'serial-{self.label}.log').write_bytes(self.output)
        self.temp.cleanup()


def observe(vm, pattern, start=0, timeout=60):
    """Wait for an unordered trace, including bytes already received."""
    deadline = time.monotonic() + timeout
    regex = re.compile(pattern)
    while True:
        match = regex.search(vm.output, start)
        if match:
            vm.consumed = max(vm.consumed, match.end())
            return match
        if time.monotonic() >= deadline or vm.vm.poll() is not None:
            raise RuntimeError(f'{vm.label}: missing trace {pattern!r}')
        try:
            chunk = vm.serial.recv(16384)
            if not chunk: raise RuntimeError('serial disconnected')
            vm.output.extend(chunk)
            (vm.out / f'serial-{vm.label}.log').write_bytes(vm.output)
        except socket.timeout: pass


def row(vm, home, status, start=0):
    pattern = (rb'profile-chooser: row index=(\d+) name=[^\n]* status=' + status.encode() +
               rb' home=' + re.escape(home.encode()) + rb'(?:\r?\n|\s)')
    return int(observe(vm, pattern, start).group(1))


def select(vm, index):
    # Forced chooser can initially focus a previously remembered row.
    vm.key('home')
    for _ in range(index): vm.key('down')
    vm.key('ret')


def chooser(vm, home, status='ready', flags='--choose-profile --apps-trace --scale=1'):
    start = len(vm.output)
    vm.launch(flags)
    observe(vm, rb'profile-chooser: ready rows=\d+', start)
    index = row(vm, home, status, start)
    return start, index


def opened(vm, home, start, profile_id=d.ID):
    observe(vm, rb'profile-chooser: remember saved home=' + re.escape(home.encode()), start)
    observe(vm, rb'deskd: profile id=' + profile_id.encode() + rb' home=' + re.escape(home.encode()) +
            rb' credentials=unchanged', start)
    observe(vm, rb'deskd: commit', start)


def restored(vm, home):
    start = len(vm.output)
    vm.launch('--apps-trace --scale=1')
    observe(vm, rb'profile-chooser: remembered restored home=' + re.escape(home.encode()), start)
    observe(vm, rb'deskd: profile id=' + d.ID.encode() + rb' home=' + re.escape(home.encode()) +
            rb' credentials=unchanged', start)
    observe(vm, rb'deskd: commit', start)
    if b'profile-chooser: ready rows=' in vm.output[start:]:
        raise RuntimeError(f'{vm.label}: restored session showed chooser')
    vm.close_desktop()


def back(vm, start, button=False):
    if button:
        pw, ph = min(vm.width - 48, 760), min(vm.height - 88, 680)
        px, py = (vm.width - pw) // 2, (vm.height - ph) // 2 + 6
        vm.click(px + pw - 96, py + ph - 33)
    else:
        vm.key('esc')
    observe(vm, rb'profile-chooser: backconsole', start)
    vm.wait(b'srv> ')
    if b'deskd: profile id=' in vm.output[start:]:
        raise RuntimeError(f'{vm.label}: chooser launched a profile unexpectedly')


def expected_choice(home, profile_id=d.ID):
    payload = f'srvros-desktop-profile-v1\n{profile_id}\n{home}\n'.encode()
    return payload + f'{zlib.crc32(payload):08x}\n'.encode()


def absent(fixture, path):
    try: fixture.read(path)
    except StopIteration: return
    raise RuntimeError(f'unexpected file: {path}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--qemu', default='qemu-system-x86_64')
    parser.add_argument('--ovmf', default=default_ovmf_path())
    parser.add_argument('--ovmf-vars', required=True)
    parser.add_argument('--boot-wait', type=int, default=120)
    args = parser.parse_args()
    if not 10 <= args.boot_wait <= 240: parser.error('invalid boot wait')
    for firmware in (args.ovmf, args.ovmf_vars):
        if not Path(firmware).is_file() or ',' in firmware: parser.error('invalid firmware path')
    base = ROOT / 'build/review/profile-chooser'; base.mkdir(parents=True, exist_ok=True)
    out = Path(tempfile.mkdtemp(prefix='proof-', dir=base))
    print(f'Profile chooser evidence: {out}', flush=True)
    receipt = {'status': 'INCOMPLETE', 'source': source_provenance.capture(ROOT),
               'firmware_sha256': d.digest(Path(args.ovmf).read_bytes()),
               'firmware_vars_sha256': d.digest(Path(args.ovmf_vars).read_bytes()),
               'qemu_version': subprocess.check_output([args.qemu, '--version'], text=True).splitlines()[0],
               'tool_sha256': {name: d.digest((ROOT / 'tools' / name).read_bytes()) for name in
                   ('profile_chooser_smoke.py', 'profile_guest_smoke.py', 'profile_desktop_smoke.py',
                    'profile_image.py', 'profile_bundle.py', 'installation_image.py')}}
    d.save_json(out / 'receipt.json', receipt)
    try:
        receipt['build'] = d.verified_build(ROOT)
        driver = ROOT / 'build/tests/profile-image-driver'
        base_volume = ROOT / 'build/srvros.exfat'
        machine_a, machine_b = d.machine_preferences(4, -300), d.machine_preferences(2, 60)
        source_first = out / 'source-first.exfat'
        profile_image.provision(base_volume, source_first, d.make_bundle(), A, 'local_a', 1001, 1001, driver, machine_a)
        alternative = d.make_bundle()
        alternative['profile'] = {'id': ALT_ID, 'display_name': 'Alternative profile'}
        source = out / 'source.exfat'
        profile_image.provision(source_first, source, alternative, ALT, 'alternative', 1002, 1002, driver)
        # B initially has no profile; import must consume A's actual guest export.
        target = out / 'destination.exfat'
        with tempfile.TemporaryDirectory(prefix='.profile-image-', dir=out) as temporary:
            stage = Path(temporary) / 'image'; shutil.copyfile(base_volume, stage)
            prefs = Path(temporary) / 'prefs'; prefs.write_bytes(machine_b)
            for op, path, extra in (('ensure-home', '/fat/home', []),
                                    ('write-desktop', '/fat/home/desktop.conf', [str(prefs)]),
                                    ('check-clean', '/fat/home', [])):
                subprocess.run([str(driver), str(stage), op, path, *extra], check=True)
            shutil.copyfile(stage, target)
        disks, bounds = {}, {}
        receipt['installations'] = {}
        for name, volume in (('a', source), ('b', target), ('transport', base_volume)):
            stage = out / ('target-' + name)
            installation_image.prepare(stage, ROOT / 'build/kernel/srvros.elf',
                ROOT / 'build/limine-binary/BOOTX64.EFI', volume,
                ROOT / 'build/userspace/init.elf', identity_bound=True)
            ready = installation_image.apply(stage)
            disk = stage / 'image.img'; disks[name] = disk
            _, (offset, size) = d.partitions(disk)
            bounds[name] = d.outside_data(disk, offset, size)
            receipt['installations'][name] = {'disk': str(disk), 'gpt': ready['gpt'],
                'data_offset': offset, 'data_bytes': size, 'protected_regions': bounds[name],
                'initial_disk_sha256': d.digest(disk.read_bytes())}
        if len({v['gpt']['disk_guid'] for v in receipt['installations'].values()}) != 3:
            raise RuntimeError('installed and transport disk GUIDs must differ')
        d.save_json(out / 'receipt.json', receipt)
        guest.check_allocation(disks['a'], out, 'a-initial')
        initial_b = guest.check_allocation(disks['b'], out, 'b-initial')
        absent(initial_b, 'home/local-b/profile.id')
        absent(guest.check_allocation(disks['transport'], out, 'transport-initial'), 'transfer.json')
        guest.boot(disks['a'], disks['transport'], out, 'a-export', args, 'export')
        exported = guest.check_allocation(disks['transport'], out, 'transport-export').read('transfer.json')
        (out / 'guest-export.json').write_bytes(exported)
        bundle = profile_bundle.decode_json(exported); payloads = profile_bundle.validate_bundle(bundle)
        if (bundle['profile']['id'] != d.ID or payloads.get('Documents/migration.txt') != d.EDITED or
            payloads.get('Documents/binary.dat') != d.BINARY or
            bundle['preferences'] != dict(d.make_bundle()['preferences'], theme_style=1)):
            raise RuntimeError('guest export mismatch')
        receipt['guest_export'] = {'path': str(out / 'guest-export.json'), 'sha256': d.digest(exported)}
        d.save_json(out / 'receipt.json', receipt)

        with VM(disks['a'], disks['transport'], out, 'a-choose', args) as vm:
            start, index = chooser(vm, A); vm.screenshot('chooser')
            select(vm, index); opened(vm, A, start); vm.close_desktop(); vm.finish()
        a_choice = guest.check_allocation(disks['a'], out, 'a-choice').read('home/.desktop-profile')
        with VM(disks['a'], disks['transport'], out, 'a-restored', args) as vm:
            restored(vm, A); vm.finish()
        # A valid remembered UUID/home whose profile disappeared must not
        # silently select legacy HOME. This disposable copy keeps A intact.
        stale = out / 'stale-a.img'; shutil.copyfile(disks['a'], stale)
        with VM(stale, disks['transport'], out, 'a-stale', args) as vm:
            vm.run('/fat/bin/rm ' + A + '/profile.id')
            start, index = chooser(vm, ALT, flags='--apps-trace --scale=1')
            select(vm, index); opened(vm, ALT, start, ALT_ID); vm.close_desktop(); vm.finish()
        stale_fixture = guest.check_allocation(stale, out, 'a-stale')
        absent(stale_fixture, 'home/local-a/profile.id')
        if stale_fixture.read('home/.desktop-profile') != expected_choice(ALT, ALT_ID):
            raise RuntimeError('stale choice was not replaced by alternative')
        if d.outside_data(stale, *d.partitions(stale)[1]) != bounds['a']:
            raise RuntimeError('stale disk protected bytes changed')
        with VM(disks['a'], disks['transport'], out, 'a-explicit', args) as vm:
            start = len(vm.output)
            vm.launch('--profile=' + ALT + ' --apps-trace --scale=1')
            observe(vm, rb'deskd: profile id=' + ALT_ID.encode() + rb' home=' + re.escape(ALT.encode()), start)
            observe(vm, rb'deskd: commit', start)
            if b'profile-chooser: ready rows=' in vm.output[start:]:
                raise RuntimeError('explicit profile unexpectedly showed chooser')
            vm.close_desktop(); vm.finish()
        if guest.check_allocation(disks['a'], out, 'a-explicit').read('home/.desktop-profile') != a_choice:
            raise RuntimeError('explicit profile changed remembered selection')
        # Missing and malformed remember records must present the chooser, with a
        # usable ready row and an explicit path back to the console.
        with VM(disks['a'], disks['transport'], out, 'a-missing', args) as vm:
            vm.run('/fat/bin/rm /fat/home/.desktop-profile')
            start, index = chooser(vm, ALT, flags='--apps-trace --scale=1')
            select(vm, index); opened(vm, ALT, start, ALT_ID); vm.close_desktop(); vm.finish()
        # Mutate A in the guest, then copy only its offline data partition into
        # a newly prepared identity-bound installation with a 640x480 EFI mode.
        with VM(disks['a'], disks['transport'], out, 'a-corrupt-choice', args) as vm:
            vm.run('/fat/bin/write /fat/home/.desktop-profile malformed'); vm.finish()
        _, (a_offset, a_size) = d.partitions(disks['a'])
        small_volume = out / 'small-source.exfat'
        small_volume.write_bytes(d.data_image(disks['a'], a_offset, a_size))
        small_stage = out / 'target-small'
        original_config = installation_image.CONFIG
        small_config = original_config.replace(b'resolution: 1280x800', b'resolution: 640x480')
        if small_config == original_config: raise RuntimeError('EFI resolution override failed')
        try:
            installation_image.CONFIG = small_config
            small_plan = installation_image.prepare(small_stage, ROOT / 'build/kernel/srvros.elf',
                ROOT / 'build/limine-binary/BOOTX64.EFI', small_volume,
                ROOT / 'build/userspace/init.elf', identity_bound=True)
            small_ready = installation_image.apply(small_stage)
        finally:
            installation_image.CONFIG = original_config
        small = small_stage / 'image.img'
        _, (small_offset, small_size) = d.partitions(small)
        small_bounds = d.outside_data(small, small_offset, small_size)
        if small_ready['gpt']['disk_guid'] in {v['gpt']['disk_guid'] for v in receipt['installations'].values()}:
            raise RuntimeError('small fixture disk GUID is not distinct')
        config = small_plan['config'].encode('ascii')
        if b'resolution: 640x480' not in config or (small_stage / 'limine.conf').read_bytes() != config:
            raise RuntimeError('small fixture EFI config mismatch')
        receipt['small_fixture'] = {'disk': str(small), 'gpt': small_ready['gpt'],
            'source_data_sha256': d.digest(small_volume.read_bytes()),
            'config': config.decode('ascii'), 'config_sha256': d.digest(config),
            'protected_regions': small_bounds, 'initial_disk_sha256': d.digest(small.read_bytes())}
        d.save_json(out / 'receipt.json', receipt)
        with VM(small, disks['transport'], out, 'a-malformed-small', args, 640, 480) as vm:
            start, _ = chooser(vm, A, flags='--apps-trace --scale=1')
            vm.screenshot('chooser-small'); back(vm, start, button=True)
            # A selected session provides the deskd framebuffer trace in
            # addition to QMP's independent screenshot-dimension check.
            start, index = chooser(vm, A, flags='--apps-trace --scale=1')
            select(vm, index); opened(vm, A, start)
            observe(vm, rb'deskd: display physical=640x480 logical=640x480 scale=1', start)
            vm.close_desktop(); vm.finish()
        if d.outside_data(small, small_offset, small_size) != small_bounds:
            raise RuntimeError('small fixture protected disk bytes changed')
        guest.check_allocation(small, out, 'small-final')
        receipt['small_fixture']['final_disk_sha256'] = d.digest(small.read_bytes())
        d.save_json(out / 'receipt.json', receipt)
        with VM(disks['a'], disks['transport'], out, 'a-reselect', args) as vm:
            start, index = chooser(vm, A, flags='--apps-trace --scale=1')
            select(vm, index); opened(vm, A, start); vm.close_desktop(); vm.finish()
        a_choice = guest.check_allocation(disks['a'], out, 'a-reselected').read('home/.desktop-profile')

        # Two B copies diverge only after an actual interrupted guest import.
        guest.boot(disks['b'], disks['transport'], out, 'b-interrupt', args, 'interrupt', 'identity')
        blocked = out / 'blocked-b.img'; shutil.copyfile(disks['b'], blocked)
        with VM(disks['b'], disks['transport'], out, 'b-recover', args) as vm:
            start, index = chooser(vm, B, 'recoverable'); vm.screenshot('recoverable')
            select(vm, index)
            observe(vm, rb'profile-chooser: recovery start home=' + re.escape(B.encode()), start)
            vm.screenshot('recovery-in-progress')
            vm.key('home')
            recovery = observe(vm, rb'profile-chooser: recovery result=success home=' + re.escape(B.encode()), start, 120)
            if b'deskd: profile id=' in vm.output[start:recovery.start()]:
                raise RuntimeError('pending profile opened before recovery completed')
            index = row(vm, B, 'ready', start)
            select(vm, index); opened(vm, B, start); vm.close_desktop(); vm.finish()
        with VM(disks['b'], disks['transport'], out, 'b-restored', args) as vm:
            restored(vm, B); vm.finish()
        if guest.check_allocation(disks['a'], out, 'a-after-b').read('home/.desktop-profile') != a_choice:
            raise RuntimeError('B selection changed A selection')
        with VM(blocked, disks['transport'], out, 'b-corrupt', args) as vm:
            vm.run('/fat/bin/write /fat/home/local-b.profile-import.json malformed')
            vm.finish()
        with VM(blocked, disks['transport'], out, 'b-blocked', args) as vm:
            blocked_before = vm.quiesced_data_hash()
            start, index = chooser(vm, B, 'blocked'); vm.screenshot('blocked')
            select(vm, index); time.sleep(1); back(vm, start)
            if b'profile-chooser: recovery start' in vm.output[start:]:
                raise RuntimeError('blocked journal started recovery')
            blocked_after = vm.quiesced_data_hash()
            if blocked_after != blocked_before:
                raise RuntimeError('blocked chooser changed data partition bytes')
            receipt['blocked_data_sha256'] = blocked_before
            vm.finish()
        blocked_fixture = guest.check_allocation(blocked, out, 'b-blocked')
        if blocked_fixture.read('home/local-b.profile-import.json') != b'malformed\n':
            raise RuntimeError('blocked journal was modified')
        if d.outside_data(blocked, *d.partitions(blocked)[1]) != bounds['b']:
            raise RuntimeError('blocked disk protected bytes changed')

        for name, disk in disks.items():
            _, (offset, size) = d.partitions(disk)
            if d.outside_data(disk, offset, size) != bounds[name]: raise RuntimeError(f'{name}: protected bytes changed')
            receipt['installations'][name]['final_disk_sha256'] = d.digest(disk.read_bytes())
        if guest.check_allocation(disks['transport'], out, 'transport-final').read('transfer.json') != exported:
            raise RuntimeError('transport bundle changed')
        for name, home, machine, binding in (('a', A, machine_a, {'alias': 'local_a', 'uid': 1001, 'gid': 1001}),
                                             ('b', B, machine_b, {'alias': 'local_b', 'uid': 2050, 'gid': 2051})):
            fixture = guest.check_allocation(disks[name], out, name + '-final')
            prefix = home.removeprefix('/fat/') + '/'
            if fixture.read(prefix + 'profile.id') != b'srvros-profile-v1\n' + d.ID.encode() + b'\n':
                raise RuntimeError(f'{name}: profile identity mismatch')
            if profile_bundle.decode_json(fixture.read(prefix + 'profile-local.json')) != binding:
                raise RuntimeError(f'{name}: local binding mismatch')
            if (fixture.read(prefix + 'Documents/migration.txt') != d.EDITED or
                fixture.read(prefix + 'Documents/binary.dat') != d.BINARY or
                profile_bundle.decode_json(fixture.read(prefix + profile_bundle.PREF_PATH)) != bundle['preferences'] or
                fixture.read('home/desktop.conf') != machine):
                raise RuntimeError(f'{name}: portable or machine data mismatch')
            absent(fixture, prefix + '.profile-import-pending')
            for binary in ('deskd', 'desktools', 'deskterm', 'profile'):
                if fixture.read('bin/' + binary) != runtime_elf((ROOT / f'build/userspace/{binary}.elf').read_bytes()):
                    raise RuntimeError(f'{name}: installed {binary} differs from build')
            choice = fixture.read('home/.desktop-profile')
            if choice != expected_choice(home):
                raise RuntimeError(f'{name}: remembered choice lacks home or identity')
            receipt['installations'][name]['profile'] = {'id': d.ID, 'home': home, 'binding': binding,
                'choice_sha256': d.digest(choice), 'machine_sha256': d.digest(machine)}
        receipt.update(status='PASS', limits=['disposable QEMU images only', 'no authentication or access-control claim',
            'no physical disk or power-loss acceptance', 'external fsck.exfat not run'])
    except Exception as error:
        receipt.update(status='FAIL', error=f'{type(error).__name__}: {error}')
        raise
    finally:
        d.save_json(out / 'receipt.json', receipt)
    print(f'profile-chooser: PASS; evidence {out}', flush=True)


