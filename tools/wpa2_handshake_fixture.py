#!/usr/bin/env python3
"""Synthetic independent WPA2 fixture,never reads local credentials/hardware."""
import hashlib
import hmac
from cryptography.hazmat.primitives.keywrap import aes_key_wrap

PMK = bytes(range(32))
AA = bytes.fromhex('020102030405')
SPA = bytes.fromhex('02060708090a')
AN = bytes(range(1, 33))
SN = bytes(range(40, 72))
RSNE = bytes.fromhex('30140100000fac040100000fac040100000fac020000')
GTK = bytes(range(80, 96))
CONTEXT = min(AA, SPA) + max(AA, SPA) + min(AN, SN) + max(AN, SN)
PTK = b''.join(hmac.digest(PMK, b'Pairwise key expansion\0' + CONTEXT + bytes([c]), 'sha1') for c in range(3))[:48]


def packet(info, replay, nonce=AN, data=b'', version=2, key_length=16, rsc=bytes(8)):
    frame = bytearray(bytes([version, 3]) + (95 + len(data)).to_bytes(2, 'big') + bytes([2]) + info.to_bytes(2, 'big') + key_length.to_bytes(2, 'big') + replay.to_bytes(8, 'big') + nonce + bytes(16) + rsc + bytes(8 + 16) + len(data).to_bytes(2, 'big') + data)
    if info & 0x100:
        frame[81:97] = hmac.digest(PTK[:16], frame, 'sha1')[:16]
    return bytes(frame)


def plaintext(rsne=RSNE, gtk=GTK, extra=b''):
    data = rsne + bytes.fromhex('dd16000fac010100') + gtk + extra
    pad = (-len(data)) % 8
    return data + (b'\xdd' + bytes(pad - 1) if pad else b'')


M1 = packet(0x008A, 7)
M2 = packet(0x010A, 7, SN, RSNE, key_length=0)
M3 = packet(0x13CA, 8, data=aes_key_wrap(PTK[16:32], plaintext()), rsc=bytes.fromhex('0102030405060000'))
M4 = packet(0x030A, 8, bytes(32), key_length=0)


def header():
    lines = ['/* Generated by tools/wpa2_handshake_fixture.py;synthetic public keys only. */']
    for name in ('PMK', 'AA', 'SPA', 'AN', 'SN', 'RSNE', 'GTK', 'PTK', 'M1', 'M2', 'M3', 'M4'):
        value = globals()[name]
        lines.append('static const unsigned char hs_' + name.lower() + '[]={' + ','.join(f'0x{x:02x}' for x in value) + '};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    import sys
    sys.stdout.write(header())
