#!/usr/bin/env python3
"""Regenerate the checked-in grayscale atlas; Pillow is needed only here.

No runtime font parser or host font dependency is introduced into the OS build.
The atlas contains ASCII, Latin-1, punctuation, and a replacement glyph.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "userspace/lib/assets/fonts/DejaVuSans.ttf"
OUT = ROOT / "userspace/lib/src/desk_font.c"
POINTS = list(range(32, 127)) + list(range(160, 256)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0xfffd]


def main():
    lines = ["/* Generated by tools/make_desktop_font.py; do not edit.",
             f" * DejaVu Sans SHA256: {hashlib.sha256(FONT.read_bytes()).hexdigest()}",
             " * Font license: userspace/lib/assets/fonts/LICENSE-DejaVu.txt */",
             '#include <srvros/desk_render.h>',
             'const char desk_font_license[] = ' + json.dumps(
                 (FONT.parent / "LICENSE-DejaVu.txt").read_text()) + ';']
    for size in (16, 20):
        font = ImageFont.truetype(str(FONT), size, layout_engine=ImageFont.Layout.BASIC)
        pixels, glyphs = [], []
        ascent, descent = font.getmetrics()
        for cp in POINTS:
            char = chr(cp)
            x0, y0, x1, y1 = font.getbbox(char, anchor="ls")
            w, h = x1-x0, y1-y0
            offset = len(pixels)
            if w and h:
                im = Image.new("L", (w, h))
                ImageDraw.Draw(im).text((-x0, -y0), char, font=font, fill=255, anchor="ls")
                pixels.extend(im.tobytes())
            glyphs.append((cp, offset, w, h, x0, y0, round(font.getlength(char))))
        lines.append(f"static const uint8_t alpha_{size}[] = {{")
        for start in range(0, len(pixels), 24):
            lines.append("    " + ",".join(map(str, pixels[start:start+24])) + ",")
        lines += ["};", f"static const struct desk_glyph glyphs_{size}[] = {{"]
        lines.extend("    {" + ",".join(map(str, g)) + "}," for g in glyphs)
        lines += ["};", f"const struct desk_font desk_font_{size} = {{glyphs_{size}, alpha_{size}, {len(glyphs)}, {ascent}, {ascent+descent+3}}};"]
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
